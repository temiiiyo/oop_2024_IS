from mesto import Mesto

class Vagon:
    # Конструктор класса Vagon, инициализирует идентификатор вагона, тип вагона и список мест
    def __init__(self, id, vagon_type):
        self.id = id  # Уникальный идентификатор вагона (например, 101, 102 и т.д.)
        self.type = vagon_type  # Тип вагона (например, "купейный", "платформенный")
        self.mesta = []  # Список мест в вагоне (изначально пустой)

    # Метод для добавления места в список мест вагона
    def add_mesto(self, mesto):
        self.mesta.append(mesto)  # Добавляем переданное место в список

    # Метод для отображения информации о вагоне
    def __str__(self):
        # Возвращает строковое представление вагона с его идентификатором, типом и количеством мест
        return f"Вагон {self.id}, Тип: {self.type}, Места: {len(self.mesta)}"

    # Метод для сравнения двух вагонов
    def __eq__(self, other):
        # Сравнивает вагоны по идентификатору (возвращает True, если идентификаторы совпадают)
        return self.id == other.id
